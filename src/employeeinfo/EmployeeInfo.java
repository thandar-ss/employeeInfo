    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        String firstName, lastName, city, phone, salary;
        firstName = txtFirstName.getText();
        lastName = txtLastName.getText();
        city = txtCity.getText();
        phone = txtPhone.getText();
        salary = txtSalary.getText();
        
        try {
            pst = con.prepareStatement("INSERT INTO records (FirstName, LastName, City, Phone, Salary) VALUES (?,?,?,?,?)");
            
            pst.setString(1,firstName);
            pst.setString(2,lastName);
            pst.setString(3, city);
            pst.setString(4,phone);
            pst.setString(5,salary);
            
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Record Saved.");
            tbl_update();
            
            txtFirstName.setText("");
            txtLastName.setText("");
            txtCity.setText("");
            txtPhone.setText("");
            txtSalary.setText("");
            
        } catch (SQLException ex) {
            System.getLogger(EmployeeInfo.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnEditActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditActionPerformed
        // TODO add your handling code here:
        int id;
        String firstName, lastName, city, phone, salary;
        
        DefaultTableModel model = (DefaultTableModel) tblRecord.getModel();
        int selectedRowIndex = tblRecord.getSelectedRow();
        
        id = Integer.parseInt(model.getValueAt(selectedRowIndex, 0).toString());
        
        firstName = txtFirstName.getText();
        lastName = txtLastName.getText();
        city = txtCity.getText();
        phone = txtPhone.getText();
        salary = txtSalary.getText();
        
        try {
            pst = con.prepareStatement("UPDATE records SET FirstName=?, LastName=?, City=?, Phone=?, Salary=? WHERE Id=?");
            
            pst.setString(1,firstName);
            pst.setString(2,lastName);
            pst.setString(3, city);
            pst.setString(4,phone);
            pst.setString(5,salary);
            pst.setInt(6,id);
            
            pst.executeUpdate();
            JOptionPane.showMessageDialog(this, "Updated.");
            tbl_update();
            
            txtFirstName.setText("");
            txtLastName.setText("");
            txtCity.setText("");
            txtPhone.setText("");
            txtSalary.setText("");
            
        } catch (SQLException ex) {
            System.getLogger(EmployeeInfo.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }   
        
    }//GEN-LAST:event_btnEditActionPerformed

