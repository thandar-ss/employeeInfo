    private void tbl_update() {
        try {
            pst = con.prepareStatement("SELECT * FROM records");
            ResultSet rs = pst.executeQuery();
            
            ResultSetMetaData rsmd = rs.getMetaData();
            int cc = rsmd.getColumnCount();
            DefaultTableModel dft = (DefaultTableModel) tblRecord.getModel();
            dft.setRowCount(0);
            
            while(rs.next()){
                Vector v = new Vector();
                
                for(int i=0;i<cc;i++){
                    v.add(rs.getString("Id"));
                    v.add(rs.getString("FirstName"));
                    v.add(rs.getString("LastName"));
                    v.add(rs.getString("City"));
                    v.add(rs.getString("Phone"));
                    v.add(rs.getString("Salary"));
                }
                dft.addRow(v);
            }
        } catch (SQLException ex) {
            System.getLogger(EmployeeInfo.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
    }
    
